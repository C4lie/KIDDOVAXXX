<#
.SYNOPSIS
    RFID Reader Diagnostic Utility ? READ ONLY
    Identifies and tests the SYRIS RD-series reader (VID_0E6A/PID_030F).

.DESCRIPTION
    This script:
      1. Confirms the RFID reader is present in Device Manager
      2. Displays its current USB mode and driver binding
      3. Monitors keyboard-wedge output in real time (HID keyboard mode)
      4. Timestamps and logs each card read event

    SAFETY GUARANTEE: This script performs zero write operations.
    It cannot write to any card, modify any card UID, lock bits, OTP fields,
    or authentication keys. It only reads from the Windows device layer.

.NOTES
    Author  : KiddoVax Diagnostic Suite
    Device  : SYRIS Technology RD-series (VID_0E6A / PID_030F)
    Requires: Windows PowerShell 5.1+ or PowerShell 7+
    Driver  : None needed (uses built-in Windows HID/usbhid.sys)
#>

#Requires -Version 5.1

# ?????????????????????????????????????????????????????????????????????????????
# Constants ? never modify these without hardware documentation
# ?????????????????????????????????????????????????????????????????????????????
$READER_VID      = '0E6A'
$READER_PID      = '030F'
$READER_NAME     = 'SYRIS Technology RD-series (USB Keyboard + EasyPOD)'
$LOG_FILE        = Join-Path $PSScriptRoot "rfid_read_log_$(Get-Date -Format 'yyyyMMdd_HHmmss').txt"
$SCAN_TIMEOUT_S  = 60   # How long to wait in keyboard-monitor mode

# ?????????????????????????????????????????????????????????????????????????????
# Helpers
# ?????????????????????????????????????????????????????????????????????????????
function Write-Section {
    param([string]$Title)
    Write-Host ""
    Write-Host ("=" * 60) -ForegroundColor DarkCyan
    Write-Host "  $Title" -ForegroundColor Cyan
    Write-Host ("=" * 60) -ForegroundColor DarkCyan
}

function Write-Ok   { param([string]$Msg) Write-Host "  [OK]  $Msg" -ForegroundColor Green }
function Write-Warn { param([string]$Msg) Write-Host "  [WARN] $Msg" -ForegroundColor Yellow }
function Write-Fail { param([string]$Msg) Write-Host "  [FAIL] $Msg" -ForegroundColor Red }
function Write-Info { param([string]$Msg) Write-Host "  [INFO] $Msg" -ForegroundColor Gray }

function Write-Log {
    param([string]$Entry)
    $timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss.fff'
    "$timestamp  $Entry" | Out-File -FilePath $LOG_FILE -Append -Encoding UTF8
}

# ?????????????????????????????????????????????????????????????????????????????
# Step 1 ? Device presence check
# ?????????????????????????????????????????????????????????????????????????????
function Test-ReaderPresent {
    Write-Section "1. Device Presence Check"

    $root = Get-PnpDevice | Where-Object {
        $_.InstanceId -like "*VID_${READER_VID}*PID_${READER_PID}*" -and
        $_.Class -eq 'USB'
    }

    if (-not $root) {
        Write-Fail "Reader NOT found: VID_${READER_VID}/PID_${READER_PID}"
        Write-Info "Possible causes:"
        Write-Info "  - Reader is unplugged"
        Write-Info "  - Reader is using a different USB port"
        Write-Info "  - Firmware was switched to a mode that changes the PID"
        Write-Log "DEVICE_NOT_FOUND VID=${READER_VID} PID=${READER_PID}"
        return $false
    }

    Write-Ok "Reader detected: $READER_NAME"
    Write-Info "Instance ID : $($root.InstanceId)"
    Write-Info "Status      : $($root.Status)"
    Write-Log "DEVICE_FOUND InstanceId=$($root.InstanceId) Status=$($root.Status)"

    if ($root.Status -ne 'OK') {
        Write-Warn "Device status is '$($root.Status)' ? expected OK"
        Write-Warn "Check Device Manager for error codes on this device"
    }

    return $true
}

# ?????????????????????????????????????????????????????????????????????????????
# Step 2 ? USB mode & driver details
# ?????????????????????????????????????????????????????????????????????????????
function Show-DeviceDetails {
    Write-Section "2. USB Mode & Driver Analysis"

    $all = Get-PnpDevice | Where-Object {
        $_.InstanceId -like "*VID_${READER_VID}*PID_${READER_PID}*"
    }

    foreach ($dev in $all) {
        $props = Get-PnpDeviceProperty -InstanceId $dev.InstanceId -ErrorAction SilentlyContinue

        $driverDesc  = ($props | Where-Object { $_.KeyName -eq 'DEVPKEY_Device_DriverDesc'    }).Data
        $driverVer   = ($props | Where-Object { $_.KeyName -eq 'DEVPKEY_Device_DriverVersion' }).Data
        $busDesc     = ($props | Where-Object { $_.KeyName -eq 'DEVPKEY_Device_BusReportedDeviceDesc' }).Data
        $hwIds       = ($props | Where-Object { $_.KeyName -eq 'DEVPKEY_Device_HardwareIds'   }).Data

        Write-Host ""
        Write-Host "  Device  : $($dev.FriendlyName)" -ForegroundColor White
        Write-Host "  Class   : $($dev.Class)"
        if ($busDesc)   { Write-Host "  Firmware: $busDesc" -ForegroundColor Magenta }
        if ($driverDesc){ Write-Host "  Driver  : $driverDesc v$driverVer" }
        if ($hwIds)     { Write-Host "  HW IDs  : $(($hwIds | Select-Object -First 2) -join ' | ')" }
    }

    Write-Host ""
    Write-Ok "Current mode: HID Keyboard Emulation (plug-and-play)"
    Write-Info "In this mode, card UIDs are 'typed' as keystrokes."
    Write-Info "No custom driver is required or installed."
    Write-Warn "Write operations are NOT available in HID keyboard mode."
    Write-Info "To enable writing, switch to USB HID RAW mode using the SYRIS RD200/300 Tool."

    Write-Log "MODE=HID_KEYBOARD_EMULATION WRITE_CAPABLE=FALSE"
}

# ?????????????????????????????????????????????????????????????????????????????
# Step 3 ? Smart Card service status
# ?????????????????????????????????????????????????????????????????????????????
function Show-ServiceStatus {
    Write-Section "3. Windows Smart Card Service Status"

    $services = @('SCardSvr','ScDeviceEnum','SCPolicySvc')
    foreach ($name in $services) {
        try {
            $svc = Get-Service -Name $name -ErrorAction Stop
            $color = if ($svc.Status -eq 'Running') { 'Green' } else { 'Yellow' }
            Write-Host "  $($svc.DisplayName): " -NoNewline
            Write-Host $svc.Status -ForegroundColor $color
        } catch {
            Write-Info "Service '$name' not queryable (permission restriction)"
        }
    }

    Write-Host ""
    Write-Info "Smart Card services are STOPPED ? this is NORMAL for HID-mode RFID readers."
    Write-Info "The reader does NOT use the PC/SC stack in keyboard emulation mode."
    Write-Log "SCARD_SERVICES=STOPPED (expected for HID mode)"
}

# ?????????????????????????????????????????????????????????????????????????????
# Step 4 ? Real-time HID keyboard output monitor
# ?????????????????????????????????????????????????????????????????????????????
function Start-HidMonitor {
    Write-Section "4. Real-Time Card Read Monitor (HID Keyboard Mode)"

    Write-Host ""
    Write-Host "  ??????????????????????????????????????????????????????" -ForegroundColor DarkGreen
    Write-Host "  ?  INSTRUCTIONS                                       ?" -ForegroundColor DarkGreen
    Write-Host "  ?  1. This window must remain FOCUSED                 ?" -ForegroundColor Green
    Write-Host "  ?  2. Place a card flat on the reader center          ?" -ForegroundColor Green
    Write-Host "  ?  3. A successful read produces a beep + typed UID   ?" -ForegroundColor Green
    Write-Host "  ?  4. Press Ctrl+C to stop monitoring                 ?" -ForegroundColor Green
    Write-Host "  ??????????????????????????????????????????????????????" -ForegroundColor DarkGreen
    Write-Host ""
    Write-Warn "IMPORTANT: The reader types the UID as keyboard input."
    Write-Warn "Keep this PowerShell window focused ? do NOT click elsewhere."
    Write-Host ""

    Write-Log "MONITOR_START timeout=${SCAN_TIMEOUT_S}s"

    # Use .NET Console.ReadKey to capture what the HID keyboard types
    # The reader sends the UID + VK_RETURN (Enter key)
    $buffer    = [System.Text.StringBuilder]::new()
    $deadline  = [DateTime]::Now.AddSeconds($SCAN_TIMEOUT_S)
    $readCount = 0

    Write-Host "  Monitoring for $SCAN_TIMEOUT_S seconds... (Ctrl+C to stop early)" -ForegroundColor Gray
    Write-Host ""

    try {
        while ([DateTime]::Now -lt $deadline) {
            if ([System.Console]::KeyAvailable) {
                $key = [System.Console]::ReadKey($true)  # $true = suppress echo

                if ($key.Key -eq [System.ConsoleKey]::Enter) {
                    # End of card UID transmission
                    $uid = $buffer.ToString().Trim()
                    $buffer.Clear() | Out-Null

                    if ($uid.Length -gt 0) {
                        $readCount++
                        $ts = Get-Date -Format 'HH:mm:ss.fff'
                        Write-Host "  [$ts] CARD READ #$readCount ? UID: " -NoNewline -ForegroundColor White
                        Write-Host $uid -ForegroundColor Yellow
                        Write-Log "CARD_READ uid=$uid length=$($uid.Length)"
                    }
                } elseif ($key.Key -eq [System.ConsoleKey]::C -and
                          ($key.Modifiers -band [System.ConsoleModifiers]::Control)) {
                    break
                } else {
                    # Accumulate keystrokes into UID buffer
                    $buffer.Append($key.KeyChar) | Out-Null
                }
            }
            Start-Sleep -Milliseconds 10
        }
    } catch [System.OperationCanceledException] {
        # Expected on Ctrl+C
    }

    Write-Host ""
    if ($readCount -gt 0) {
        Write-Ok "$readCount card read(s) captured during monitoring."
        Write-Info "Your reader and card frequencies match ? hardware is working."
        Write-Info "Next step: use SYRIS RD200/300 Tool to switch modes if writing is needed."
    } else {
        Write-Warn "No card reads detected during the monitoring window."
        Write-Info "Possible causes:"
        Write-Info "  1. Card frequency does not match reader (most common)"
        Write-Info "  2. Card was not held flat against the reader antenna"
        Write-Info "  3. PowerShell window lost focus (HID input went elsewhere)"
        Write-Info "  4. Card chip is not in the reader's supported list"
        Write-Info ""
        Write-Info "Check physical label on reader for: RD200-LF (125kHz) or RD200-M1 (13.56MHz)"
        Write-Info "Then match your card to that frequency."
    }

    Write-Log "MONITOR_END reads=$readCount"
}

